const mineflayer = require("mineflayer");
const { connect, consoleCmd, botCmd, sleep, waitUntil, settle } = require("./harness");
(async () => {
  const { bot, agent } = await connect("ChestBot");
  const s = mineflayer.createBot({ host: "localhost", port: 25599, username: "Steve", auth: "offline", version: "26.1.2" });
  await new Promise((r) => s.once("spawn", r));
  consoleCmd("op Steve"); consoleCmd("difficulty peaceful"); consoleCmd("time set day"); consoleCmd("gamemode survival ChestBot");
  consoleCmd("tp ChestBot 150 90 -150"); await settle(bot);
  const b = bot.entity.position.floored();
  consoleCmd(`fill ${b.x - 30} ${b.y - 10} ${b.z - 30} ${b.x + 30} ${b.y + 10} ${b.z + 30} air replace chest`); await sleep(800);
  await botCmd(bot, "clear @s");
  const cx = b.x + 7, cy = b.y, cz = b.z + 3;
  consoleCmd(`setblock ${cx} ${cy} ${cz} chest`); await sleep(1500);
  consoleCmd(`item replace block ${cx} ${cy} ${cz} container.0 with minecraft:diamond 5`); await sleep(500);
  consoleCmd(`item replace block ${cx} ${cy} ${cz} container.1 with minecraft:rotten_flesh 3`); await sleep(500);
  consoleCmd(`item replace block ${cx} ${cy} ${cz} container.5 with minecraft:iron_ingot 12`); await sleep(500);
  consoleCmd(`setblock ${cx} ${cy - 1} ${cz} stone`);
  await sleep(1500);
  agent.run();
  const heard = []; s.on("chat", (u, m) => { if (u === "ChestBot") heard.push(m); });
  const n = (k) => bot.inventory.items().filter((i) => i.name === k).reduce((a, i) => a + i.count, 0);
  const results = [];
  s.chat("ChestBot what is in the chest");
  await waitUntil(() => heard.some((m) => /Chest had|chest is empty/i.test(m)), 30000, 300);
  results.push(["list", heard.some((m) => /5 diamond/.test(m)) && n("diamond") === 0]);
  s.chat("ChestBot open the chest and take all the items");
  const ok = await waitUntil(() => n("diamond") === 5 && n("iron_ingot") === 12, 40000, 400);
  results.push(["take_all", ok && n("rotten_flesh") === 3]);
  s.chat("ChestBot put the iron ingot in the chest");
  results.push(["put", await waitUntil(() => n("iron_ingot") === 0, 40000, 400)]);
  console.log(JSON.stringify(results), "said:", JSON.stringify(heard));
  agent.stop(); bot.quit(); s.quit(); process.exit(results.every((r) => r[1]) ? 0 : 1);
})();
